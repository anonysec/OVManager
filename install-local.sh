#!/usr/bin/env bash
# install-local.sh — local dev installer for a working tree.
#
# Fast rerun loop: validate src -> rsync to dest -> minimal .env and unit ->
# uv sync -> restart -> loopback health. Rerunning updates in place.
# Dev-only: no docker, no ACME, no backups, no rollback, no release fetch.
# install.sh and manager.sh are frozen; this file never touches them.
set -euo pipefail

SERVICE=ovmanager.service
UNIT=/etc/systemd/system/$SERVICE
DEST=/opt/ovmanager
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UNINSTALL=0

die() { echo "install-local: $*" >&2; exit 1; }

usage() {
    cat <<'EOF'
install-local.sh — local dev installer (rerun = update)

  --src DIR     source tree (default: directory of this script)
  --dest DIR    destination (default: /opt/ovmanager)
  --uninstall   stop the service and remove the destination
  --help        show this help
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --src) [[ $# -ge 2 ]] || die "--src needs a directory"; SRC=$2; shift 2 ;;
        --dest) [[ $# -ge 2 ]] || die "--dest needs a directory"; DEST=$2; shift 2 ;;
        --uninstall) UNINSTALL=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) die "unknown flag: $1 (try --help)" ;;
    esac
done

# rm -rf lives behind this: an empty or / destination is never intended.
assert_dest_safe() {
    [[ -n "$DEST" && "$DEST" != "/" ]] || die "refusing to operate on '$DEST'"
}

if [[ $UNINSTALL == 1 ]]; then
    [[ $EUID -eq 0 ]] || die "must run as root"
    assert_dest_safe
    systemctl stop "$SERVICE" >/dev/null 2>&1 || true
    systemctl disable "$SERVICE" >/dev/null 2>&1 || true
    rm -f "$UNIT"
    systemctl daemon-reload
    rm -rf "$DEST"
    echo "install-local: removed $DEST"
    exit 0
fi

# Validation runs before the root gate so a broken tree reports its real
# reason and `--help`/bad flags work for whoever ran them.
[[ -d "$SRC" ]] || die "no source directory: $SRC"
[[ -f "$SRC/main.py" ]] || die "no main.py in $SRC"
[[ -d "$SRC/frontend/dist" ]] || die "frontend/dist missing — run: cd frontend && npm run build"
[[ $EUID -eq 0 ]] || die "must run as root"
assert_dest_safe
command -v rsync >/dev/null || die "rsync not found"
command -v uv >/dev/null || die "uv not found"

# .env is excluded so a dest credential file is never overwritten by a rerun
# (--delete alone would not touch an excluded file).
rsync -a --delete \
    --exclude .git \
    --exclude .venv \
    --exclude __pycache__ \
    --exclude node_modules \
    --exclude .pytest_cache \
    --exclude .slim \
    --exclude .env \
    --exclude /data \
    "$SRC/" "$DEST/"

# Recreate the venv the rsync exclude drops (frozen lockfile, no dev deps).
(cd "$DEST" && uv sync --frozen --no-dev)

mkdir -p "$DEST/data"
# Never copy the source tree's .env: dev trees carry real ADMIN_PASSWORD_HASH
# values and the v16 migration would import one as the owner password,
# leaving a "fresh" panel claimed with an unknown credential.
if [[ ! -f "$DEST/.env" ]]; then
    cat > "$DEST/.env" <<EOF
# Generated by install-local.sh. Kept across reruns, never overwritten.
PORT=2095
DATA_DIR=$DEST/data
ADMIN_USERNAME=admin
EOF
fi
chmod 600 "$DEST/.env"
# Claim key is create-once like .env: reruns must never invalidate it.
if [[ ! -f "$DEST/data/owner-claim.key" ]]; then
    key="$(openssl rand -hex 32 2>/dev/null | cut -c1-32 || head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n' | cut -c1-32)"
    ( umask 077; printf '%s\n' "$key" > "$DEST/data/owner-claim.key" )
    chmod 600 "$DEST/data/owner-claim.key"
    echo "install-local: setup key (shown once, then claim in the panel): $key"
fi
PORT="$(awk -F= '/^PORT=/{print $2; exit}' "$DEST/.env" | tr -d '\r')"
PORT="${PORT:-2095}"

# The venv interpreter, not `uv run`: uv re-resolves the project on every
# start, which cannot write into the tree a service account does not own.
cat > "$UNIT" <<UNIT
[Unit]
Description=OVManager panel (install-local.sh dev install)
After=network.target

[Service]
Type=simple
WorkingDirectory=$DEST
EnvironmentFile=$DEST/.env
Environment="DATA_DIR=$DEST/data"
ExecStart=$DEST/.venv/bin/python main.py
Restart=on-failure
RestartSec=3

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl restart "$SERVICE"

# Fail open: a slow panel is a warning, not a failed install.
health=""
for _ in $(seq 1 30); do
    if curl -fsS --max-time 2 "http://127.0.0.1:$PORT/health" >/dev/null 2>&1; then
        health=1
        break
    fi
    sleep 1
done
[[ -n "$health" ]] || echo "install-local: warning: no /health on port $PORT yet — check: systemctl status $SERVICE" >&2
echo "install-local: installed $DEST (port $PORT)"
